class MockSerial:
    """Mock serial connection generating 1 Hz background frames and command responses."""
    def __init__(self):
        self._rx_buffer = []
        self._lock = threading.Lock()
        self._running = True

        self._thread = threading.Thread(target=self._generate_1hz_stream, daemon=True)
        self._thread.start()

    def _generate_1hz_stream(self):
        while self._running:
            with self._lock:
                for line in HEX_STREAM_FRAME.strip().split('\n'):
                    self._rx_buffer.append((line + '\n').encode('ascii'))
            time.sleep(1.0)

    def write(self, data: bytes):
        cmd = data.decode("ascii", errors="replace").strip()
        print(f"    [MockSerial Tx] -> {cmd}")
        
        with self._lock:
            if cmd.lower() == "p":
                for line in P_COMMAND_RESPONSE.split('\n'):
                    self._rx_buffer.append((line + '\n').encode('ascii'))
            else:
                self._rx_buffer.append(b"OK!\r\n")

    def readline(self) -> bytes:
        start_time = time.time()
        while time.time() - start_time < 1.5:
            with self._lock:
                if self._rx_buffer:
                    return self._rx_buffer.pop(0)
            time.sleep(0.05)
        return b""

    def close(self):
        self._running = False
        print("    [MockSerial] Closed connection.")
